func TestMCPMoveColdRetryCannotReestablishScope(t *testing.T) {
	store, err := sqlitestore.Open(t.Context(), filepath.Join(t.TempDir(), "kata.db"))
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, store.Close()) })
	source, err := store.CreateProject(t.Context(), "source-project")
	require.NoError(t, err)
	target, err := store.CreateProject(t.Context(), "target-project")
	require.NoError(t, err)
	root, _, err := store.CreateIssue(t.Context(), db.CreateIssueParams{ProjectID: source.ID, Title: "Root", Author: "tester"})
	require.NoError(t, err)
	outside, err := store.CreateProject(t.Context(), "outside-project")
	require.NoError(t, err)
	child, _, err := store.CreateIssue(t.Context(), db.CreateIssueParams{ProjectID: outside.ID, Title: "Completed child", Author: "tester"})
	require.NoError(t, err)
	_, err = store.CreateLink(t.Context(), db.CreateLinkParams{FromIssueID: child.ID, ToIssueID: root.ID, Type: "parent", Author: "tester"})
	require.NoError(t, err)
	_, _, _, err = store.CloseIssue(t.Context(), child.ID, "done", "tester", "", nil)
	require.NoError(t, err)
	server := daemon.NewServer(daemon.ServerConfig{DB: store, StartedAt: time.Now().UTC()})
	t.Cleanup(func() { require.NoError(t, server.Close()) })
	httpServer := httptest.NewServer(server.Handler())
	t.Cleanup(httpServer.Close)
	client, err := kataclient.NewWithHTTPClient(httpServer.URL, httpServer.Client())
	require.NoError(t, err)
	scope, err := NewAllowlistScope([]ProjectIdentity{{ID: source.ID, UID: source.UID, Name: source.Name}, {ID: target.ID, UID: target.UID, Name: target.Name}})
	require.NoError(t, err)
	session := connectTestServerWithOptions(t, Options{Client: client, Scope: scope, Actor: "tester", Version: "test"})
	requestUID, err := uid.New()
	require.NoError(t, err)
	preview, err := client.MoveIssueTree(t.Context(), &generated.MoveIssueTreeRequestOptions{Body: &generated.MoveIssueTreeBody{DryRun: new(true), Request: generated.MoveTreeRequest{SourceAuthorityUID: store.InstanceUID(), SourceProjectUID: source.UID, IssueUID: root.UID, DestinationAuthorityUID: store.InstanceUID(), DestinationProjectUID: target.UID, ActorAuthorityUID: store.InstanceUID(), Actor: "tester", RequestUID: requestUID}}})
	require.NoError(t, err)
	committedRequest := generated.MoveTreeRequest{SourceAuthorityUID: store.InstanceUID(), SourceProjectUID: source.UID, IssueUID: root.UID, DestinationAuthorityUID: store.InstanceUID(), DestinationProjectUID: target.UID, ActorAuthorityUID: store.InstanceUID(), Actor: "tester", RequestUID: requestUID, PreviewDigest: &preview.Preview.Digest}
	moved, err := client.MoveIssueTree(t.Context(), &generated.MoveIssueTreeRequestOptions{Body: &generated.MoveIssueTreeBody{Request: committedRequest}})
	require.NoError(t, err)
	require.Equal(t, "completed", moved.Result.State)
	cursor, err := store.MaxEventID(t.Context())
	require.NoError(t, err)
	result, err := session.CallTool(t.Context(), &sdkmcp.CallToolParams{Name: "kata.move", Arguments: map[string]any{"ref": source.Name + "#" + root.UID, "to_project": target.Name, "request_uid": requestUID, "preview_digest": preview.Preview.Digest}})
	require.NoError(t, err)
	require.False(t, result.IsError, "%s", mustJSON(t, result))
	structured, ok := result.StructuredContent.(map[string]any)
	require.True(t, ok)
	require.Equal(t, "outcome-unknown", structured["state"], "a cold retry never widens startup source scope")
	after, err := store.MaxEventID(t.Context())
	require.NoError(t, err)
	require.Equal(t, cursor, after, "unverifiable scope does not write or manufacture another move event")
}
