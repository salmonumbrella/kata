func TestMCPMoveWholeTreeIncludesCompletedChildren(t *testing.T) {
	store, err := sqlitestore.Open(t.Context(), filepath.Join(t.TempDir(), "kata.db"))
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, store.Close()) })
	source, err := store.CreateProject(t.Context(), "source-project")
	require.NoError(t, err)
	target, err := store.CreateProject(t.Context(), "target-project")
	require.NoError(t, err)
	root, _, err := store.CreateIssue(t.Context(), db.CreateIssueParams{ProjectID: source.ID, Title: "Root", Author: "tester"})
	require.NoError(t, err)
	child, _, err := store.CreateIssue(t.Context(), db.CreateIssueParams{ProjectID: source.ID, Title: "Completed child", Author: "tester"})
	require.NoError(t, err)
	_, err = store.CreateLink(t.Context(), db.CreateLinkParams{FromIssueID: child.ID, ToIssueID: root.ID, Type: "parent", Author: "tester"})
	require.NoError(t, err)
	_, _, _, err = store.CloseIssue(t.Context(), child.ID, "done", "tester", "", nil)
	require.NoError(t, err)
	server := daemon.NewServer(daemon.ServerConfig{DB: store, StartedAt: time.Now().UTC()})
	t.Cleanup(func() { require.NoError(t, server.Close()) })
	httpServer := httptest.NewServer(server.Handler())
	t.Cleanup(httpServer.Close)
	client, err := kataclient.NewWithHTTPClient(httpServer.URL, httpServer.Client())
	require.NoError(t, err)
	scope, err := NewAllowlistScope([]ProjectIdentity{{ID: source.ID, UID: source.UID, Name: source.Name}, {ID: target.ID, UID: target.UID, Name: target.Name}})
	require.NoError(t, err)
	session := connectTestServerWithOptions(t, Options{Client: client, Scope: scope, Actor: "tester", Version: "test"})
	result := callWorkflowTool(t, session, "kata.move", map[string]any{"ref": source.Name + "#" + root.ShortID, "to_project": target.Name})
	require.Equal(t, "completed", result["state"], "MCP exposes the typed move outcome")
	stored, err := store.IssueByUID(t.Context(), child.UID, db.IncludeDeletedYes)
	require.NoError(t, err)
	require.Equal(t, target.ID, stored.ProjectID)
}

